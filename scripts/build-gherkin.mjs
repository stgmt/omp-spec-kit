import { readFile, mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = new URL("../", import.meta.url);
const output = new URL("src/kernel/vendor/gherkin.js", root);
const packages = ["@cucumber/gherkin", "@cucumber/messages"];
const notices = await Promise.all(packages.map(async (name) => {
  const manifest = JSON.parse(await readFile(new URL(`node_modules/${name}/package.json`, root), "utf8"));
  const license = await readFile(new URL(`node_modules/${name}/LICENSE`, root), "utf8");
  return `// ${name}@${manifest.version}\n${license.trimEnd().split(/\r?\n/u).map((line) => `// ${line}`.trimEnd()).join("\n")}`;
}));
const result = await build({
  absWorkingDir: fileURLToPath(root),
  stdin: {
    contents: [
      'export { Parser, AstBuilder, GherkinClassicTokenMatcher, compile } from "@cucumber/gherkin";',
      'export { IdGenerator } from "@cucumber/messages";',
    ].join("\n"),
    resolveDir: fileURLToPath(root),
  },
  bundle: true,
  format: "esm",
  platform: "node",
  target: "node22",
  legalComments: "inline",
  banner: { js: ["// Generated by scripts/build-gherkin.mjs.", ...notices].join("\n") },
  write: false,
});
const bytes = Buffer.from(result.outputFiles[0].contents);
if (process.argv.includes("--check")) {
  const current = await readFile(output);
  if (!current.equals(bytes)) throw new Error("Run node scripts/build-gherkin.mjs to refresh the Gherkin module");
} else {
  await mkdir(new URL("./", output), { recursive: true });
  await writeFile(output, bytes);
}
