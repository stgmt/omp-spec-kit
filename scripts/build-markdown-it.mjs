import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = new URL("../", import.meta.url);
const output = new URL("src/kernel/vendor/markdown-it.js", root);
const licenses = [
  ["markdown-it", "LICENSE"],
  ["entities", "LICENSE"],
  ["mdurl", "LICENSE"],
  ["linkify-it", "LICENSE"],
  ["punycode.js", "LICENSE-MIT.txt"],
  ["uc.micro", "LICENSE.txt"],
];
const notices = await Promise.all(licenses.map(async ([name, filename]) => {
  const manifest = JSON.parse(await readFile(new URL(`node_modules/${name}/package.json`, root), "utf8"));
  const license = await readFile(new URL(`node_modules/${name}/${filename}`, root), "utf8");
  return `// ${name}@${manifest.version}\n${license.trimEnd().split(/\r?\n/u).map((line) => `// ${line}`.trimEnd()).join("\n")}`;
}));
const result = await build({
  absWorkingDir: fileURLToPath(root),
  stdin: {
    contents: 'export { default } from "markdown-it";',
    resolveDir: fileURLToPath(root),
  },
  bundle: true,
  format: "esm",
  platform: "node",
  target: "node22",
  // Upstream documentation includes CommonJS examples; retain legal notices
  // and remove ordinary comments from the closed ESM payload.
  minifyWhitespace: true,
  legalComments: "inline",
  banner: { js: ["// Generated by scripts/build-markdown-it.mjs.", ...notices].join("\n") },
  metafile: true,
  write: false,
});

// Refuse a dependency change that would omit its license from the bundle.
const bundledPackages = new Set();
for (const input of Object.keys(result.metafile.inputs)) {
  const parts = input.replaceAll("\\", "/").split("/");
  const index = parts.indexOf("node_modules");
  if (index < 0) continue;
  if (parts.indexOf("node_modules", index + 1) >= 0) throw new Error(`Nested dependency needs an explicit license notice: ${input}`);
  const name = parts[index + 1].startsWith("@") ? `${parts[index + 1]}/${parts[index + 2]}` : parts[index + 1];
  bundledPackages.add(name);
}
const expectedPackages = new Set(licenses.map(([name]) => name));
if (bundledPackages.size !== expectedPackages.size || [...bundledPackages].some((name) => !expectedPackages.has(name))) {
  throw new Error(`Markdown bundle dependencies changed; update license notices: ${[...bundledPackages].sort().join(", ")}`);
}
const imports = Object.values(result.metafile.outputs).flatMap((entry) => entry.imports);
if (imports.length > 0) throw new Error(`Markdown bundle is not self-contained: ${imports.map((entry) => entry.path).join(", ")}`);

const bytes = Buffer.from(result.outputFiles[0].contents);
if (process.argv.includes("--check")) {
  const current = await readFile(output);
  if (!current.equals(bytes)) throw new Error("Run node scripts/build-markdown-it.mjs to refresh the Markdown module");
} else {
  await mkdir(new URL("./", output), { recursive: true });
  await writeFile(output, bytes);
}
